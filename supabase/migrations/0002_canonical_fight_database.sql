-- Canonical, source-audited historical UFC fight database.
-- This migration supplements the original prototype tables; it does not delete them.

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  event_name text,
  event_date date not null,
  location text,
  source_name text,
  source_url text,
  created_at timestamptz not null default now(),
  unique(event_name,event_date)
);
create index if not exists events_event_date_idx on public.events(event_date);

create table if not exists public.fighter_aliases (
  id bigint generated by default as identity primary key,
  fighter_id bigint not null references public.fighters(id) on delete cascade,
  alias text not null,
  normalized_alias text not null unique,
  source_name text,
  source_url text,
  verified boolean not null default false
);

create table if not exists public.canonical_fights (
  id bigint generated by default as identity primary key,
  canonical_key text not null unique,
  event_id bigint references public.events(id),
  event_date date not null,
  fighter_a_id bigint not null references public.fighters(id),
  fighter_b_id bigint not null references public.fighters(id),
  winner_fighter_id bigint references public.fighters(id),
  outcome_category text not null check (outcome_category in ('fighter_a_win','fighter_b_win','draw','no_contest','unknown')),
  method text,
  finish_round integer,
  finish_time text,
  weight_class text,
  title_fight boolean,
  referee text,
  bout_details text,
  record_status text not null default 'needs_review' check (record_status in ('needs_review','verified','disputed','excluded')),
  verification_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (fighter_a_id <> fighter_b_id)
);
create index if not exists canonical_fights_event_date_idx on public.canonical_fights(event_date);
create index if not exists canonical_fights_fighter_a_idx on public.canonical_fights(fighter_a_id);
create index if not exists canonical_fights_fighter_b_idx on public.canonical_fights(fighter_b_id);

create table if not exists public.fight_source_records (
  id bigint generated by default as identity primary key,
  fight_id bigint not null references public.canonical_fights(id) on delete cascade,
  source_name text not null,
  source_url text,
  source_record_id text not null,
  source_license text,
  retrieved_at timestamptz not null default now(),
  raw_payload jsonb not null,
  match_confidence numeric(5,4) not null default 1 check (match_confidence between 0 and 1),
  unique(source_name, source_record_id)
);

create table if not exists public.fight_data_review_queue (
  id bigint generated by default as identity primary key,
  fight_id bigint references public.canonical_fights(id) on delete cascade,
  issue_type text not null,
  severity text not null default 'warning' check (severity in ('info','warning','blocking')),
  details jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending','resolved','dismissed')),
  issue_key text unique,
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

-- A fighter receives a separate score for their side of each bout.
create table if not exists public.fighter_fight_scores (
  id bigint generated by default as identity primary key,
  fight_id bigint not null references public.canonical_fights(id) on delete cascade,
  fighter_id bigint not null references public.fighters(id) on delete cascade,
  opponent_id bigint not null references public.fighters(id),
  opponent_quality numeric(5,2) check (opponent_quality between 0 and 34),
  opponent_form numeric(5,2) check (opponent_form between 0 and 11),
  outcome_quality numeric(5,2) check (outcome_quality between 0 and 18),
  finish_timing numeric(5,2) check (finish_timing between 0 and 7),
  context_score numeric(5,2) check (context_score between 0 and 5),
  total_score numeric(6,2) generated always as
    (coalesce(opponent_quality,0)+coalesce(opponent_form,0)+coalesce(outcome_quality,0)+coalesce(finish_timing,0)+coalesce(context_score,0)) stored,
  evidence jsonb not null default '[]'::jsonb,
  calculation_version text not null default 'V2.5',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  unique(fight_id, fighter_id, calculation_version),
  check (fighter_id <> opponent_id)
);

alter table public.events enable row level security;
alter table public.fighter_aliases enable row level security;
alter table public.canonical_fights enable row level security;
alter table public.fight_source_records enable row level security;
alter table public.fight_data_review_queue enable row level security;
alter table public.fighter_fight_scores enable row level security;

-- Public read access is limited to verified fight records and approved score rows.
create policy "Public reads verified canonical fights" on public.canonical_fights
for select using (record_status = 'verified');
create policy "Public reads approved fighter fight scores" on public.fighter_fight_scores
for select using (status = 'approved');

