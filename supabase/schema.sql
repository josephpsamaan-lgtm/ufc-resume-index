-- UFC Résumé Index database foundation.
-- Enable Supabase Auth and create an explicit admin authorization policy
-- before allowing any administrative writes. Never expose service_role keys.

create table if not exists public.fighters (
  id bigint generated by default as identity primary key,
  canonical_name text not null unique,
  slug text not null unique,
  division text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.fights (
  id bigint generated by default as identity primary key,
  fighter_id bigint not null references public.fighters(id) on delete cascade,
  opponent_name text not null,
  opponent_id bigint references public.fighters(id),
  event_name text,
  event_date date,
  result text check (result in ('win','loss','draw','no_contest','other')),
  method text,
  round integer,
  time text,
  source_name text,
  source_url text,
  source_record_id text,
  historical_rank_at_fight text,
  raw_payload jsonb not null default '{}'::jsonb,
  verified boolean not null default false,
  unique (source_name, source_record_id, fighter_id)
);

create table if not exists public.fight_scores (
  id bigint generated by default as identity primary key,
  fight_id bigint not null references public.fights(id) on delete cascade,
  opponent_quality numeric(5,2) not null check (opponent_quality between 0 and 34),
  opponent_form numeric(5,2) not null check (opponent_form between 0 and 11),
  outcome_quality numeric(5,2) not null check (outcome_quality between 0 and 18),
  finish_timing numeric(5,2) not null check (finish_timing between 0 and 7),
  context_score numeric(5,2) not null check (context_score between 0 and 5),
  total_score numeric(6,2) generated always as
    (opponent_quality + opponent_form + outcome_quality + finish_timing + context_score) stored,
  evidence jsonb not null default '[]'::jsonb,
  audit_notes text,
  calculation_version text not null default 'V2.5',
  approved boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (fight_id, calculation_version)
);

create table if not exists public.career_scores (
  fighter_id bigint primary key references public.fighters(id) on delete cascade,
  quality_of_wins numeric(5,2) not null default 0 check (quality_of_wins between 0 and 10),
  championship_resume numeric(5,2) not null default 0 check (championship_resume between 0 and 6),
  consistency numeric(5,2) not null default 0 check (consistency between 0 and 6),
  quality_of_losses numeric(5,2) not null default 0 check (quality_of_losses between 0 and 3),
  total_score numeric(6,2) generated always as
    (quality_of_wins + championship_resume + consistency + quality_of_losses) stored,
  evidence jsonb not null default '[]'::jsonb,
  audit_notes text,
  calculation_version text not null default 'V2.5',
  approved boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.ranking_publications (
  id bigint generated by default as identity primary key,
  fighter_id bigint not null references public.fighters(id) on delete cascade,
  score numeric(7,4) not null check (score between 0 and 100),
  rank integer,
  calculation_version text not null default 'V2.5',
  approved_by uuid,
  approved_at timestamptz,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  published boolean not null default false
);

create table if not exists public.score_review_queue (
  id bigint generated by default as identity primary key,
  fighter_id bigint not null references public.fighters(id) on delete cascade,
  previous_score numeric(7,4),
  proposed_score numeric(7,4) not null check (proposed_score between 0 and 100),
  calculation_version text not null default 'V2.5',
  change_summary text not null,
  evidence jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.data_sync_log (
  id bigint generated by default as identity primary key,
  provider text not null,
  sync_started_at timestamptz not null default now(),
  sync_finished_at timestamptz,
  status text not null default 'pending',
  records_seen integer not null default 0,
  records_changed integer not null default 0,
  error_message text
);

alter table public.fighters enable row level security;
alter table public.fights enable row level security;
alter table public.fight_scores enable row level security;
alter table public.career_scores enable row level security;
alter table public.ranking_publications enable row level security;
alter table public.score_review_queue enable row level security;
alter table public.data_sync_log enable row level security;

create policy "Public reads fighter directory" on public.fighters
for select using (true);

create policy "Public reads verified fight records" on public.fights
for select using (verified = true);

create policy "Public reads approved fight scores" on public.fight_scores
for select using (approved = true);

create policy "Public reads approved career scores" on public.career_scores
for select using (approved = true);

create policy "Public reads published ranking snapshots" on public.ranking_publications
for select using (published = true);

